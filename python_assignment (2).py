# Program to calculate factorial iteratively
def calculate_factorial(n):
  if n < 0:
    return "Factorial is not defined for negative numbers."
  elif n == 0 or n == 1:
    return 1

  result = 1
  for i in range(2, n + 1):
    result *= i
  return result


# Test the function
num = 5
print(f"Factorial of {num} is: {calculate_factorial(num)}")